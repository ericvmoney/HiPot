"""US place to metro region lookup, shared by the collector and anything else
that needs to turn "City, ST" into a metro id from taxonomy.yml.

The lookup table `data/geo/places.json` is generated by `tools/build_metros.py`
from Census Bureau files; do not edit it by hand.

    from pipeline.geo import metro_for
    metro_for("Weirton", "WV")      # -> "pittsburgh-pa"
    metro_for("Milford", "UT")      # -> None (not in any metro region)
"""
from __future__ import annotations

import json
import re
import unicodedata
from functools import lru_cache

from pipeline.io import ROOT

PLACES_FILE = ROOT / "data" / "geo" / "places.json"

# Leading abbreviations that job boards and the Census spell differently.
_ABBREVIATIONS = {"st": "saint", "ste": "sainte", "ft": "fort", "mt": "mount", "pt": "point"}


def normalise_place(name: str) -> str:
    """A matching key for a place name: lower case, no accents or punctuation,
    and 'St.', 'Ft.', 'Mt.' spelled out, so 'St. Louis' and 'Saint Louis' agree."""
    text = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode("ascii").lower()
    text = text.replace("&", " and ")
    words = re.sub(r"[^a-z0-9]+", " ", text).split()
    return " ".join(_ABBREVIATIONS.get(word, word) for word in words)


@lru_cache(maxsize=1)
def _places() -> dict[str, dict[str, str]]:
    return json.loads(PLACES_FILE.read_text(encoding="utf-8"))["places"]


def metro_for(city: str | None, state: str | None) -> str | None:
    """The metro region id for a US city and two-letter state code, or None when
    the place is outside every metro region, unknown, or ambiguous."""
    if not city or not state:
        return None
    return _places().get(state.upper(), {}).get(normalise_place(city))
